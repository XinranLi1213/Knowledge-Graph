const {createRequire}=require('node:module');
const path=require('node:path');
const fs=require('node:fs');
const req=createRequire(path.join(path.dirname(process.execPath),'..','node_modules','runtime.js'));
const {chromium}=req('playwright');
(async()=>{
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--disable-gpu']});
const page=await browser.newPage({viewport:{width:1512,height:982}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8765');
await page.waitForSelector('g.node');
const check=async(condition,message)=>{if(!await condition)throw Error(message);};
await check(page.locator('g.node').count().then(n=>n===30),'initial overview');
await page.locator('[data-mode="diagnosis"]').click();
await check(page.locator('g.node path.risk').count().then(n=>n>0),'risk outline');
await page.locator('g.node').filter({has:page.locator('title',{hasText:'通信电子线路'})}).first().click();
await check(page.locator('#sidebar').innerText().then(t=>t.includes('49.7')&&t.includes('50%')),'C05 sidebar');
await page.screenshot({path:'review/desktop-preview.png',fullPage:true});
const position=await page.locator('g.node').first().getAttribute('transform');
await page.locator('[data-mode="structure"]').click();
await check(page.locator('g.node').first().getAttribute('transform').then(v=>v===position),'mode layout stability');
await page.selectOption('#scenario','course_totals_only');
await page.waitForFunction(()=>document.querySelector('#visible-count').textContent.startsWith('30 '));
await page.waitForTimeout(400);
await page.locator('[data-mode="diagnosis"]').click();
await page.locator('#expand').click();
await check(page.locator('g.node').count().then(n=>n===138),'all knowledge');
await check(page.locator('g.node path.pending').count().then(n=>n===108),'course totals missing knowledge');
await page.locator('#search').fill('快速傅里叶');
await page.locator('#search-results button').first().click();
await check(page.locator('#sidebar h2').innerText().then(t=>t==='快速傅里叶变换'),'knowledge search');
await page.locator('#filters-toggle').click();
await page.selectOption('#course',['C01']);await page.selectOption('#health',['red']);
await check(page.locator('#empty').isVisible(),'empty filters');
await page.locator('#empty-reset').click();
await page.selectOption('#scenario','knowledge_full');await page.waitForTimeout(600);
await page.locator('#search').fill('电路分析');await page.locator('#search-results button').first().click();
await check(page.locator('#sidebar').innerText().then(t=>t.includes('间接后继')),'indirect successors');
await page.locator('#chain').click();
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
await page.screenshot({path:'review/mobile-preview.png',fullPage:true});
await check(page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile overflow');
await check(Promise.resolve(errors.length===0),'runtime errors: '+errors.join('\n'));
fs.writeFileSync('review/browser-check.json',JSON.stringify({status:'passed',browser:'Chrome headless',checks:['overview','risk outline','C05 score/coverage','stable mode layout','all nodes','course total null knowledge','search','empty filters/reset','indirect successors','chain','mobile width','no runtime errors']},null,2));
console.log('Browser checks passed');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
